"""
Stage 2B - Spectral Characterization of IMU PSD
================================================

Reads the median PSD files generated by Stage 2A:

    f2_median_psd.csv
    f3_median_psd.csv
    f5_median_psd.csv

Computes, for each flight and IMU axis:

    1. Band RMS
    2. Total RMS
    3. HF RMS
    4. HF fraction
    5. Spectral centroid
    6. Spectral bandwidth
    7. Spectral 95% frequency
    8. Dominant frequency
    9. Relative band powers

IMPORTANT:
    - No raw IMU data is reloaded.
    - No interpolation.
    - No resampling.
    - No filtering.
    - This script only analyzes the already-computed PSD.
    - HF cutoff is exploratory and configurable.
    - The final vibration band is NOT selected automatically.

Default exploratory HF definitions:

    HF_10_100Hz
    HF_20_100Hz
    HF_50_100Hz

This allows us to compare different definitions before
selecting the final vibration metric.
"""

