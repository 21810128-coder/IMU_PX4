# ============================================================
# HELPER FUNCTIONS
# ============================================================

def clean_psd(f, psd):
    """
    Clean frequency / PSD arrays.

    Keeps:
        finite frequency
        finite PSD
        frequency >= 0
        PSD >= 0
    """

    f = np.asarray(
        f,
        dtype=float
    )

    psd = np.asarray(
        psd,
        dtype=float
    )

    mask = (
        np.isfinite(f)
        & np.isfinite(psd)
        & (f >= 0.0)
        & (psd >= 0.0)
    )

    f = f[mask]
    psd = psd[mask]

    # Sort by frequency
    order = np.argsort(f)

    f = f[order]
    psd = psd[order]

    # Remove duplicate frequencies
    unique_f, unique_idx = np.unique(
        f,
        return_index=True
    )

    psd = psd[unique_idx]
    f = unique_f

    return f, psd


def integrate_power(
    f,
    psd,
    low,
    high
):
    """
    Integrate PSD over a frequency interval.

    Power = integral PSD(f) df

    Returns variance-like quantity.
    """

    mask = (
        (f >= low)
        & (f <= high)
    )

    if np.sum(mask) < 2:
        return np.nan

    f_band = f[mask]
    psd_band = psd[mask]

    if len(f_band) < 2:
        return np.nan

    return np.trapezoid(
        psd_band,
        f_band
    )


def rms_from_power(power):
    """
    Convert integrated PSD power to RMS.
    """

    if not np.isfinite(power):
        return np.nan

    if power < 0:
        return np.nan

    return np.sqrt(power)


def spectral_centroid(
    f,
    psd
):
    """
    PSD-weighted spectral centroid.

        fc = integral(f * PSD df)
             -------------------
             integral(PSD df)
    """

    total_power = integrate_power(
        f,
        psd,
        f[0],
        f[-1]
    )

    if (
        not np.isfinite(total_power)
        or total_power <= 0
    ):
        return np.nan

    numerator = np.trapezoid(
        f * psd,
        f
    )

    return numerator / total_power


def spectral_bandwidth(
    f,
    psd,
    centroid=None
):
    """
    PSD-weighted spectral bandwidth.

        BW = sqrt(
            integral(
                (f - fc)^2 PSD df
            )
            /
            integral(
                PSD df
            )
        )
    """

    if centroid is None:
        centroid = spectral_centroid(
            f,
            psd
        )

    if not np.isfinite(centroid):
        return np.nan

    total_power = integrate_power(
        f,
        psd,
        f[0],
        f[-1]
    )

    if (
        not np.isfinite(total_power)
        or total_power <= 0
    ):
        return np.nan

    numerator = np.trapezoid(
        ((f - centroid) ** 2) * psd,
        f
    )

    variance = numerator / total_power

    if variance < 0:
        return np.nan

    return np.sqrt(variance)


def spectral_percentile_frequency(
    f,
    psd,
    percentile=95.0
):
    """
    Frequency below which a specified percentage
    of total PSD power is contained.

    Example:
        percentile=95
        -> f95
    """

    if len(f) < 2:
        return np.nan

    # Trapezoidal cumulative integration
    df = np.diff(f)

    segment_power = (
        0.5
        * (
            psd[:-1]
            + psd[1:]
        )
        * df
    )

    cumulative_power = np.concatenate(
        [
            [0.0],
            np.cumsum(segment_power)
        ]
    )

    total_power = cumulative_power[-1]

    if (
        not np.isfinite(total_power)
        or total_power <= 0
    ):
        return np.nan

    target = (
        percentile / 100.0
    ) * total_power

    idx = np.searchsorted(
        cumulative_power,
        target
    )

    if idx <= 0:
        return f[0]

    if idx >= len(f):
        return f[-1]

    # Linear interpolation
    p1 = cumulative_power[idx - 1]
    p2 = cumulative_power[idx]

    f1 = f[idx - 1]
    f2 = f[idx]

    if p2 == p1:
        return f2

    return (
        f1
        + (target - p1)
        * (f2 - f1)
        / (p2 - p1)
    )


def dominant_frequency(
    f,
    psd,
    minimum_frequency=0.5
):
    """
    Find the maximum PSD frequency above minimum_frequency.
    """

    mask = (
        (f >= minimum_frequency)
        & np.isfinite(psd)
    )

    if np.sum(mask) == 0:
        return np.nan

    f_valid = f[mask]
    psd_valid = psd[mask]

    idx = np.argmax(
        psd_valid
    )

    return f_valid[idx]


def band_fraction(
    band_power,
    total_power
):
    """
    Fraction of total PSD power in a band.
    """

    if (
        not np.isfinite(band_power)
        or not np.isfinite(total_power)
        or total_power <= 0
    ):
        return np.nan

    return (
        band_power
        / total_power
    )


# ============================================================
# PROCESS ONE AXIS
# ============================================================

def analyze_axis(
    f,
    psd,
    axis_name
):
    """
    Compute all Stage 2B metrics for one IMU axis.
    """

    f, psd = clean_psd(
        f,
        psd
    )

    result = {
        "axis": axis_name
    }

    if len(f) < 2:

        return result

    nyquist = np.max(f)

    result[
        "frequency_min_hz"
    ] = np.min(f)

    result[
        "frequency_max_hz"
    ] = nyquist

    # --------------------------------------------------------
    # Total power / RMS
    # --------------------------------------------------------

    total_power = integrate_power(
        f,
        psd,
        f[0],
        f[-1]
    )

    total_rms = rms_from_power(
        total_power
    )

    result[
        "total_power"
    ] = total_power

    result[
        "total_rms"
    ] = total_rms

    # --------------------------------------------------------
    # Spectral centroid
    # --------------------------------------------------------

    centroid = spectral_centroid(
        f,
        psd
    )

    result[
        "spectral_centroid_hz"
    ] = centroid

    # --------------------------------------------------------
    # Spectral bandwidth
    # --------------------------------------------------------

    bandwidth = spectral_bandwidth(
        f,
        psd,
        centroid
    )

    result[
        "spectral_bandwidth_hz"
    ] = bandwidth

    # --------------------------------------------------------
    # Spectral 95%
    # --------------------------------------------------------

    f95 = spectral_percentile_frequency(
        f,
        psd,
        percentile=95.0
    )

    result[
        "spectral_95_hz"
    ] = f95

    # --------------------------------------------------------
    # Dominant frequency
    # --------------------------------------------------------

    result[
        "dominant_frequency_hz"
    ] = dominant_frequency(
        f,
        psd,
        minimum_frequency=0.5
    )

    # ========================================================
    # Exploratory frequency bands
    # ========================================================

    for band_name, (
        low,
        high
    ) in BANDS.items():

        # Make sure upper limit does not
        # exceed actual PSD frequency.
        high_actual = min(
            high,
            nyquist
        )

        power = integrate_power(
            f,
            psd,
            low,
            high_actual
        )

        rms = rms_from_power(
            power
        )

        fraction = band_fraction(
            power,
            total_power
        )

        result[
            f"{band_name}_power"
        ] = power

        result[
            f"{band_name}_rms"
        ] = rms

        result[
            f"{band_name}_fraction"
        ] = fraction

    # ========================================================
    # HF metrics
    # ========================================================

    for hf_name, (
        low,
        high
    ) in HF_BANDS.items():

        high_actual = min(
            high,
            nyquist
        )

        hf_power = integrate_power(
            f,
            psd,
            low,
            high_actual
        )

        hf_rms = rms_from_power(
            hf_power
        )

        hf_fraction = band_fraction(
            hf_power,
            total_power
        )

        result[
            f"{hf_name}_power"
        ] = hf_power

        result[
            f"{hf_name}_rms"
        ] = hf_rms

        result[
            f"{hf_name}_fraction"
        ] = hf_fraction

    return result


# ============================================================
# PROCESS ONE FLIGHT
# ============================================================

def process_flight(
    flight_name,
    psd_path
):

    print("\n" + "=" * 70)
    print(
        f"Processing {flight_name}"
    )
    print("=" * 70)

    if not psd_path.exists():

        raise FileNotFoundError(
            f"PSD file not found:\n"
            f"{psd_path}"
        )

    print(
        f"Reading:\n{psd_path}"
    )

    df = pd.read_csv(
        psd_path
    )

    if "frequency_hz" not in df.columns:

        raise ValueError(
            f"{psd_path} does not contain "
            "'frequency_hz'."
        )

    f = df[
        "frequency_hz"
    ].to_numpy(
        dtype=float
    )

    records = []

    for axis_name in ALL_AXES:

        psd_column = (
            f"{axis_name}_psd"
        )

        if (
            psd_column
            not in df.columns
        ):

            print(
                f"WARNING: "
                f"{psd_column} missing"
            )

            continue

        psd = df[
            psd_column
        ].to_numpy(
            dtype=float
        )

        result = analyze_axis(
            f,
            psd,
            axis_name
        )

        result[
            "flight"
        ] = flight_name

        # Put flight first
        result = {
            "flight": result.pop(
                "flight"
            ),
            **result
        }

        records.append(
            result
        )

    result_df = pd.DataFrame(
        records
    )

    return result_df


